import { evaluateRisk, RULES_VERSION, type RiskConfig, DEFAULT_RISK_CONFIG } from "../rules.js";
import type { Scenario } from "./scenarios.js";

export interface EvalRow {
  name: string;
  label: Scenario["label"];
  score: number;
  flagged: boolean;
  rules: string[];
}

export interface EvalResult {
  rulesVersion: string;
  rows: EvalRow[];
  tp: number;
  fp: number;
  fn: number;
  tn: number;
  /** null when the denominator is zero. */
  precision: number | null;
  recall: number | null;
  f1: number | null;
  ruleHits: Record<string, { suspicious: number; legitimate: number }>;
}

function ratio(numerator: number, denominator: number): number | null {
  return denominator === 0 ? null : numerator / denominator;
}

export function evaluate(
  scenarios: readonly Scenario[],
  config: RiskConfig = DEFAULT_RISK_CONFIG,
): EvalResult {
  const rows: EvalRow[] = [];
  const ruleHits: EvalResult["ruleHits"] = {};
  let tp = 0;
  let fp = 0;
  let fn = 0;
  let tn = 0;

  for (const scenario of scenarios) {
    const result = evaluateRisk(scenario.transfer, scenario.history, config);
    const suspicious = scenario.label === "suspicious";
    if (result.flagged && suspicious) tp++;
    else if (result.flagged && !suspicious) fp++;
    else if (!result.flagged && suspicious) fn++;
    else tn++;

    for (const hit of result.reasons) {
      const entry = (ruleHits[hit.rule] ??= { suspicious: 0, legitimate: 0 });
      entry[scenario.label]++;
    }
    rows.push({
      name: scenario.name,
      label: scenario.label,
      score: result.score,
      flagged: result.flagged,
      rules: result.reasons.map((r) => r.rule),
    });
  }

  const precision = ratio(tp, tp + fp);
  const recall = ratio(tp, tp + fn);
  const f1 =
    precision === null || recall === null || precision + recall === 0
      ? null
      : (2 * precision * recall) / (precision + recall);

  return { rulesVersion: RULES_VERSION, rows, tp, fp, fn, tn, precision, recall, f1, ruleHits };
}

const pct = (value: number | null): string =>
  value === null ? "n/a" : `${(value * 100).toFixed(1)}%`;

export function renderReport(result: EvalResult): string {
  const total = result.rows.length;
  const suspicious = result.rows.filter((r) => r.label === "suspicious").length;
  const lines: string[] = [
    "# Risk rules evaluation",
    "",
    "<!-- Generated by apps/worker/scripts/risk-report.ts. Do not edit by hand. -->",
    "",
    `Rules version: \`${result.rulesVersion}\`. Flag threshold: score of ${DEFAULT_RISK_CONFIG.reviewThreshold} or more.`,
    "",
    "## What this measures",
    "",
    `${total} hand-written scenarios (${suspicious} suspicious, ${total - suspicious} legitimate).`,
    "Each label was assigned from the scenario's description before running the rules. These are",
    "constructed examples, **not production data**, so the numbers describe how the rules behave on",
    "these cases and say nothing about real-world fraud rates.",
    "",
    "## Results",
    "",
    "| | Flagged | Not flagged |",
    "| --- | ---: | ---: |",
    `| Suspicious | ${result.tp} (true positive) | ${result.fn} (missed) |`,
    `| Legitimate | ${result.fp} (false positive) | ${result.tn} (true negative) |`,
    "",
    `- Precision: **${pct(result.precision)}** (of the transfers flagged, how many were suspicious)`,
    `- Recall: **${pct(result.recall)}** (of the suspicious transfers, how many were flagged)`,
    `- F1: **${pct(result.f1)}**`,
    "",
    "## Per scenario",
    "",
    "| Scenario | Label | Score | Flagged | Rules fired |",
    "| --- | --- | ---: | --- | --- |",
    ...result.rows.map(
      (r) =>
        `| ${r.name} | ${r.label} | ${r.score} | ${r.flagged ? "yes" : "no"} | ${r.rules.join(", ") || "none"} |`,
    ),
    "",
    "## Rule hits by label",
    "",
    "| Rule | In suspicious | In legitimate |",
    "| --- | ---: | ---: |",
    ...Object.entries(result.ruleHits)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([rule, hits]) => `| ${rule} | ${hits.suspicious} | ${hits.legitimate} |`),
    "",
    "## Misses and false positives",
    "",
    ...missesSection(result),
    "",
  ];
  return lines.join("\n");
}

function missesSection(result: EvalResult): string[] {
  const missed = result.rows.filter((r) => r.label === "suspicious" && !r.flagged);
  const wrong = result.rows.filter((r) => r.label === "legitimate" && r.flagged);
  const out: string[] = [];
  out.push(
    missed.length === 0
      ? "No suspicious scenario was missed."
      : `Missed (suspicious, not flagged): ${missed.map((r) => `${r.name} (score ${r.score})`).join("; ")}.`,
  );
  out.push("");
  out.push(
    wrong.length === 0
      ? "No legitimate scenario was flagged."
      : `False positives (legitimate, flagged): ${wrong.map((r) => `${r.name} (score ${r.score})`).join("; ")}.`,
  );
  return out;
}
